CREATE TABLE IF NOT EXISTS migrations(version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS lessons(id TEXT PRIMARY KEY,body TEXT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS one_open_lesson ON lessons((1)) WHERE json_extract(body,'$.phase')!='ended';
CREATE TABLE IF NOT EXISTS students(id TEXT PRIMARY KEY,lesson_id TEXT NOT NULL REFERENCES lessons(id) ON DELETE CASCADE,body TEXT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS student_slot ON students(lesson_id,json_extract(body,'$.slot'));
CREATE TABLE IF NOT EXISTS images(id TEXT PRIMARY KEY,body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS cards(id TEXT PRIMARY KEY,student_id TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,image_id TEXT NOT NULL REFERENCES images(id),body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS progress(id TEXT PRIMARY KEY REFERENCES students(id) ON DELETE CASCADE,body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS practice(id TEXT PRIMARY KEY,student_id TEXT NOT NULL REFERENCES students(id) ON DELETE CASCADE,body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY,body TEXT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS session_token ON sessions(json_extract(body,'$.tokenHash'));
CREATE TABLE IF NOT EXISTS operations(scope TEXT NOT NULL,id TEXT NOT NULL,request_hash TEXT NOT NULL,response TEXT NOT NULL,PRIMARY KEY(scope,id));
